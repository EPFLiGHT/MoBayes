#!/bin/bash
# DDXPlus — Patient persona ablation (BMBE + GPT-5.4-nano + SA GPT-5.4-nano).
# Runs 4 personas x 2 modes (BMBE, SA) = 8 conditions, n=25 each.
# Usage: bash experiments/ddxplus/persona_ablation.sh
set -euo pipefail
source .env

DATA_DIR="data/kbs/ddxplus"
PROFILE_DIR="data/cases/ddxplus_patientsim_a"
OUTPUT="data/benchmark_results/set_a/ddxplus_patientsim/ablations"
N=25
MODEL="gpt-5.4-nano"
PATIENT="gpt-5.4-nano"

# NOTE: Persona profile directories expected at:
#   data/cases/ddxplus_patientsim_a/{overanxious,distrustful,dazed,verbose_lowrecall}/profiles.json
# These were generated by scripts/data_prep/generate_profiles.py with persona flags.

PERSONAS=("overanxious" "distrustful" "dazed" "verbose_lowrecall")

# ── Batch 1: BMBE for first 3 personas ──
echo "=== Batch 1: BMBE (overanxious, distrustful, dazed) ==="
for persona in "${PERSONAS[@]:0:3}"; do
  echo "--- BMBE + ${persona} ---"
  python3 scripts/core/benchmark_patientsim.py \
    --profiles "$PROFILE_DIR/${persona}/profiles.json" \
    --data-dir "$DATA_DIR" \
    --doctor-mode mobayes --doctor-model "$MODEL" \
    --patient-model "$PATIENT" \
    --force-max-turns --n $N \
    --output "$OUTPUT/persona_${persona}_bmbe" &
done
wait
echo "=== Batch 1 done (3 BMBE) ==="

# ── Batch 2: BMBE verbose_lowrecall + SA first 2 personas ──
echo "=== Batch 2: BMBE verbose_lowrecall + SA overanxious + SA distrustful ==="
python3 scripts/core/benchmark_patientsim.py \
  --profiles "$PROFILE_DIR/verbose_lowrecall/profiles.json" \
  --data-dir "$DATA_DIR" \
  --doctor-mode mobayes --doctor-model "$MODEL" \
  --patient-model "$PATIENT" \
  --force-max-turns --n $N \
  --output "$OUTPUT/persona_verbose_lowrecall_bmbe" &

for persona in "${PERSONAS[@]:0:2}"; do
  echo "--- SA + ${persona} ---"
  python3 scripts/core/benchmark_patientsim.py \
    --profiles "$PROFILE_DIR/${persona}/profiles.json" \
    --data-dir "$DATA_DIR" \
    --doctor-mode standalone --doctor-model "$MODEL" \
    --patient-model "$PATIENT" \
    --n $N \
    --output "$OUTPUT/persona_${persona}_sa" &
done
wait
echo "=== Batch 2 done ==="

# ── Batch 3: SA for remaining 2 personas ──
echo "=== Batch 3: SA dazed + SA verbose_lowrecall ==="
for persona in "${PERSONAS[@]:2:2}"; do
  echo "--- SA + ${persona} ---"
  python3 scripts/core/benchmark_patientsim.py \
    --profiles "$PROFILE_DIR/${persona}/profiles.json" \
    --data-dir "$DATA_DIR" \
    --doctor-mode standalone --doctor-model "$MODEL" \
    --patient-model "$PATIENT" \
    --n $N \
    --output "$OUTPUT/persona_${persona}_sa" &
done
wait
echo "=== All persona ablations done ==="
